/**
 * Downloads LXGW WenKai (Simplified Chinese) Light, Regular, and Medium from
 * the upstream GitHub release and splits each into unicode-range woff2 chunks
 * so browsers only fetch the glyphs a page uses. All weights share one
 * font-family, mapped to font-weight 400, 600, and 700 to line up with Klee
 * One, which WenKai is modeled off of. Google Fonts only carries the TC
 * variant.
 *
 * Usage: bun fonts:wenkai [tag] [--force] [--dry-run]   (see --help)
 */

import { createHash } from "node:crypto"
import { rmSync } from "node:fs"
import {
  readdir,
  readFile,
  rename,
  rm,
  stat,
  unlink,
  writeFile,
} from "node:fs/promises"
import path from "node:path"
import type { ParseArgsConfig } from "node:util"
import { parseArgs } from "node:util"

const REPO = "lxgw/LxgwWenKai"
const FAMILY = "LXGW WenKai"
// Shifted to line up with Klee One
const WEIGHTS = [
  { name: "Light", target: { name: "regular", weight: 400 } },
  { name: "Regular", target: { name: "semibold", weight: 600 } },
  { name: "Medium", target: { name: "bold", weight: 700 } },
] as const
const ROOT = path.resolve(import.meta.dirname, "..")
const SCRIPT = path.relative(ROOT, import.meta.filename)
const OUT_DIR = path.join(ROOT, "src/fonts/lxgw-wenkai")
const TMP_DIR = `${OUT_DIR}.tmp`
const CSS_FILE = "lxgw-wenkai.css"

const assetName = (name: string): string => `LXGWWenKai-${name}.ttf`

const USAGE = `Usage: bun fonts:wenkai [tag] [options]

Downloads these fonts from ${REPO} and splits them into woff2 chunks in
src/fonts/lxgw-wenkai. Defaults to the latest release.

${WEIGHTS.map((w) => `  ${assetName(w.name)}`).join("\n")}

Options:
  -f, --force    Regenerate even if the output is already at this release
  -n, --dry-run  Show what would be downloaded without writing anything
  -h, --help     Show this help

Set GITHUB_TOKEN to avoid GitHub API rate limits.`

const CONFIG = {
  options: {
    force: { type: "boolean", short: "f" },
    "dry-run": { type: "boolean", short: "n" },
    help: { type: "boolean", short: "h" },
  },
  allowPositionals: true,
} as const satisfies ParseArgsConfig

function fail(message: string): never {
  console.error(`error: ${message}`)
  process.exit(1)
}

function parseCli(): ReturnType<typeof parseArgs<typeof CONFIG>> {
  try {
    return parseArgs(CONFIG)
  } catch (error) {
    fail(`${(error as Error).message}\n\n${USAGE}`)
  }
}

const { values, positionals } = parseCli()
if (values.help) {
  console.log(USAGE)
  process.exit(0)
}
if (positionals.length > 1) {
  fail(`expected at most one tag, got: ${positionals.join(" ")}`)
}
const [tag] = positionals

const mb = (bytes: number): string => `${(bytes / 1024 / 1024).toFixed(1)} MB`

async function get(
  url: string,
  headers: Record<string, string> = {},
): Promise<Response> {
  const res = await fetch(url, { headers })
  if (res.ok) return res
  const hint =
    res.status === 403 || res.status === 429 ?
      " (rate limited? set GITHUB_TOKEN)"
    : res.status === 404 && tag ? ` (is "${tag}" a release tag in ${REPO}?)`
    : ""
  fail(`GET ${url} → ${res.status} ${res.statusText}${hint}`)
}

/** Release tag recorded in the header of the existing CSS file, if any. */
async function currentTag(): Promise<string | undefined> {
  try {
    const css = await readFile(path.join(OUT_DIR, CSS_FILE), "utf8")
    return css.match(/^\/\* .+ (\S+), generated by/)?.[1]
  } catch {
    return undefined
  }
}

const token = process.env.GITHUB_TOKEN
const releaseUrl = `https://api.github.com/repos/${REPO}/releases/${tag ? `tags/${tag}` : "latest"}`
const release = (await (
  await get(releaseUrl, {
    Accept: "application/vnd.github+json",
    ...(token ? { Authorization: `Bearer ${token}` } : {}),
  })
).json()) as {
  tag_name: string
  assets: {
    name: string
    size: number
    digest: string | null
    browser_download_url: string
  }[]
}
const fonts = WEIGHTS.map((w) => {
  const asset = release.assets.find((a) => a.name === assetName(w.name))
  if (!asset)
    fail(`${assetName(w.name)} not found in ${REPO} ${release.tag_name}`)
  return { ...w, asset }
})
const totalSize = fonts.reduce((sum, f) => sum + f.asset.size, 0)

const current = await currentTag()
if (current === release.tag_name && !values.force) {
  console.log(`Already at ${current}; pass --force to regenerate`)
  process.exit(0)
}

if (values["dry-run"]) {
  console.log(
    `Would replace ${current ?? "nothing"} with ${release.tag_name} ` +
      `(${mb(totalSize)})\n` +
      fonts
        .map(
          (f) =>
            `  ${f.asset.name} (${mb(f.asset.size)}) from ` +
            f.asset.browser_download_url,
        )
        .join("\n") +
      `\n  into ${OUT_DIR}`,
  )
  process.exit(0)
}

console.log(
  `Downloading ${fonts.map((f) => f.name).join(", ")} ${release.tag_name} ` +
    `(${mb(totalSize)})`,
)
const inputs = await Promise.all(
  fonts.map(async ({ asset }) => {
    const input = new Uint8Array(
      await (await get(asset.browser_download_url)).arrayBuffer(),
    )
    if (asset.digest) {
      const actual = `sha256:${createHash("sha256").update(input).digest("hex")}`
      if (actual !== asset.digest) {
        fail(
          `checksum mismatch for ${asset.name}: expected ${asset.digest}, ` +
            `got ${actual}`,
        )
      }
    } else {
      console.warn(
        `warning: no digest published for ${asset.name}; skipping checksum`,
      )
    }
    return input
  }),
)

// Split into a sibling directory and swap only on success so a failed run
// preserves existing files.
await rm(TMP_DIR, { recursive: true, force: true })
const onInterrupt = (): never => {
  rmSync(TMP_DIR, { recursive: true, force: true })
  process.exit(130)
}
process.once("SIGINT", onInterrupt)
try {
  // Import lazily to hide cn-font-split banner for --help, --dry-run, and
  // error output.
  const { fontSplit } = await import("cn-font-split")
  const faces: string[] = []
  // Each weight goes in its own subdirectory, then the generated CSS is merged
  // into one file with urls rebased onto that subdirectory.
  for (const [i, f] of fonts.entries()) {
    console.log(`Splitting ${f.name}`)
    const outDir = path.join(TMP_DIR, f.target.name)
    await fontSplit({
      input: inputs[i],
      outDir,
      css: {
        fontFamily: FAMILY,
        fontWeight: String(f.target.weight),
        fontDisplay: "block",
        // Full name of the installed face, so a locally installed Regular
        // isn't used for every weight
        localFamily: [f.name === "Regular" ? FAMILY : `${FAMILY} ${f.name}`],
        fileName: CSS_FILE,
      },
      testHtml: false,
      reporter: false,
      silent: true,
    })
    await unlink(path.join(outDir, "index.proto"))
    const cssPath = path.join(outDir, CSS_FILE)
    faces.push(
      (await readFile(cssPath, "utf8")).replaceAll(
        'url("./',
        `url("./${f.target.name}/`,
      ),
    )
    await unlink(cssPath)
  }

  await writeFile(
    path.join(TMP_DIR, CSS_FILE),
    `/* ${FAMILY} ${fonts.map((f) => f.name).join(", ")} ${release.tag_name}, generated by ${SCRIPT} */

${faces.join("\n\n")}

:root {
  --font-lxgw-wenkai: "${FAMILY}";
}
`,
  )
} catch (error) {
  await rm(TMP_DIR, { recursive: true, force: true })
  fail(`split failed: ${(error as Error).message}`)
}

// Once OUT_DIR is removed, TMP_DIR holds the only copy, so it must be
// preserved on interrupt
process.off("SIGINT", onInterrupt)
await rm(OUT_DIR, { recursive: true, force: true })
await rename(TMP_DIR, OUT_DIR)

const chunks = (await readdir(OUT_DIR, { recursive: true })).filter((f) =>
  f.endsWith(".woff2"),
)
let bytes = 0
for (const f of chunks) bytes += (await stat(path.join(OUT_DIR, f))).size
console.log(
  `${current ?? "none"} → ${release.tag_name}: ${chunks.length} chunks, ` +
    `${mb(bytes)} in ${path.relative(process.cwd(), OUT_DIR)}`,
)
